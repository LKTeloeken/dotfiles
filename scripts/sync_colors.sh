  if [ ! -d "$OUTPUT_DIR" ]; then
    mkdir -p "$OUTPUT_DIR"
  fi
}

write_colors_setup() {
  python3 - "$WAL_CACHE_DIR/colors.json" "$OUTPUT_FILE" "$OUTPUT_FISH_FILE" <<'PY'
import json
import sys
from pathlib import Path
import colorsys

wal_path = Path(sys.argv[1])
out_path = Path(sys.argv[2])
fish_path = Path(sys.argv[3])

fallback = {
    "background": "#1e1e2e",
    "foreground": "#cdd6f4",
    "cursor": "#f5e0dc",
    "color0": "#45475a",
    "color1": "#f38ba8",
    "color2": "#a6e3a1",
    "color3": "#f9e2af",
    "color4": "#89b4fa",
    "color5": "#f5c2e7",
    "color6": "#94e2d5",
    "color7": "#bac2de",
    "color8": "#585b70",
    "color9": "#f38ba8",
    "color10": "#a6e3a1",
    "color11": "#f9e2af",
    "color12": "#89b4fa",
    "color13": "#f5c2e7",
    "color14": "#94e2d5",
    "color15": "#a6adc8",
}

palette = dict(fallback)

if wal_path.exists():
    try:
        data = json.loads(wal_path.read_text())
        colors = data.get("colors", {})
        special = data.get("special", {})
        palette.update(colors)
        palette["background"] = special.get("background", palette.get("color0", fallback["background"]))
        palette["foreground"] = special.get("foreground", palette.get("color7", fallback["foreground"]))
        palette["cursor"] = special.get("cursor", palette.get("color5", fallback["cursor"]))
    except Exception:
        pass

def hex_to_rgb(h):
    return tuple(int(h[i:i+2], 16) / 255 for i in (1, 3, 5))

def rgb_to_hex(rgb):
    return f"#{int(rgb[0]*255):02x}{int(rgb[1]*255):02x}{int(rgb[2]*255):02x}"

def rel_luminance(h):
    def channel(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = hex_to_rgb(h)
    r, g, b = channel(r), channel(g), channel(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast_ratio(a, b):
    l1, l2 = rel_luminance(a), rel_luminance(b)
    lighter, darker = max(l1, l2), min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)

def adjust_for_contrast(color, bg, ratio=4.5):
    if contrast_ratio(color, bg) >= ratio:
        return color

    h, l, s = colorsys.rgb_to_hls(*hex_to_rgb(color))
    bg_lum = rel_luminance(bg)
    direction = 1 if bg_lum < 0.5 else -1
    step = 0.04
    last = color

    for _ in range(30):
        l = min(1.0, l + step) if direction > 0 else max(0.0, l - step)
        last = rgb_to_hex(colorsys.hls_to_rgb(h, l, s))
        if contrast_ratio(last, bg) >= ratio:
            return last

    return "#ffffff" if bg_lum < 0.5 else "#000000"

bg = palette["background"]
palette["foreground"] = adjust_for_contrast(palette["foreground"], bg, ratio=4.5)
palette["cursor"] = adjust_for_contrast(palette["cursor"], bg, ratio=4.5)

for i in list(range(1, 8)) + list(range(9, 16)):
    key = f"color{i}"
    if key in palette:
        palette[key] = adjust_for_contrast(palette[key], bg, ratio=4.5)

lines = [
    "# Autogenerated. Source this file in configs.",
    "# shellcheck disable=SC2034",
]

fish_lines = [
    "# Autogenerated. Source this file in configs.",
]

def emit(name, value):
    lines.append(f"{name}='{value}'")
    fish_lines.append(f"set -gx {name} '{value}'")

emit("BACKGROUND", palette["background"])
emit("FOREGROUND", palette["foreground"])
emit("CURSOR", palette["cursor"])
for i in range(16):
    emit(f"COLOR{i}", palette[f"color{i}"])

lines.extend([
    "",
    "# Semantic aliases",
    "COLOR_BASE=\"$BACKGROUND\"",
    "COLOR_TEXT=\"$FOREGROUND\"",
    "COLOR_SUBTEXT=\"$COLOR7\"",
    "COLOR_PRIMARY=\"$COLOR4\"",
    "COLOR_SURFACE=\"$COLOR8\"",
    "COLOR_OVERLAY=\"$COLOR8\"",
    "",
    "# Exports for apps",
    "export STARSHIP_CONFIG=\"$HOME/.config/colors/starship.toml\"",
])

fish_lines.extend([
    "",
    "# Semantic aliases",
    "set -gx COLOR_BASE \"$BACKGROUND\"",
    "set -gx COLOR_TEXT \"$FOREGROUND\"",
    "set -gx COLOR_SUBTEXT \"$COLOR7\"",
    "set -gx COLOR_PRIMARY \"$COLOR4\"",
    "set -gx COLOR_SURFACE \"$COLOR8\"",
    "set -gx COLOR_OVERLAY \"$COLOR8\"",
    "",
    "# Exports for apps",
    "set -gx STARSHIP_CONFIG \"$HOME/.config/colors/starship.toml\"",
])

out_path.write_text("\n".join(lines) + "\n")
fish_path.write_text("\n".join(fish_lines) + "\n")
PY
}

update_starship_palette() {
  python3 - "$STARSHIP_FILE" "$OUTPUT_FILE" "$STARSHIP_OUTPUT_FILE" \
    "$STARSHIP_FALLBACK_OVERLAY" "$STARSHIP_FALLBACK_LOVE" "$STARSHIP_FALLBACK_GOLD" \
    "$STARSHIP_FALLBACK_ROSE" "$STARSHIP_FALLBACK_PINE" "$STARSHIP_FALLBACK_FOAM" "$STARSHIP_FALLBACK_IRIS" <<'PY'
import colorsys
import re
import sys
from pathlib import Path

starship_path = Path(sys.argv[1])
colors_path = Path(sys.argv[2])
output_path = Path(sys.argv[3])
fallback = {
    "overlay": sys.argv[4],
    "love":    sys.argv[5],
    "gold":    sys.argv[6],
    "rose":    sys.argv[7],
    "pine":    sys.argv[8],
    "foam":    sys.argv[9],
    "iris":    sys.argv[10],
}

def parse_colors(path):
    colors = {}
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        colors[key.strip()] = value.strip().strip("'")
    return colors

def hex_to_rgb(h):
    return tuple(int(h[i:i+2], 16) / 255 for i in (1, 3, 5))

def rgb_to_hex(rgb):
    return f"#{int(rgb[0]*255):02x}{int(rgb[1]*255):02x}{int(rgb[2]*255):02x}"

def rel_luminance(h):
    def channel(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = hex_to_rgb(h)
    r, g, b = channel(r), channel(g), channel(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast_ratio(a, b):
    l1, l2 = rel_luminance(a), rel_luminance(b)
    lighter, darker = max(l1, l2), min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)

def adjust_for_contrast(color, bg, ratio=4.5):
    if contrast_ratio(color, bg) >= ratio:
        return color

    h, l, s = colorsys.rgb_to_hls(*hex_to_rgb(color))
    bg_lum = rel_luminance(bg)
    direction = 1 if bg_lum < 0.5 else -1
    step = 0.04
    last = color

    for _ in range(30):
        l = min(1.0, l + step) if direction > 0 else max(0.0, l - step)
        last = rgb_to_hex(colorsys.hls_to_rgb(h, l, s))
        if contrast_ratio(last, bg) >= ratio:
            return last

    return "#ffffff" if bg_lum < 0.5 else "#000000"

def hex_to_hsl(h):
    r, g, b = int(h[1:3], 16) / 255, int(h[3:5], 16) / 255, int(h[5:7], 16) / 255
    h_, l, s = colorsys.rgb_to_hls(r, g, b)
    return h_ * 360, s, l

def find_closest(candidates, target_hue, min_sat=0.15):
    saturated = [(c, hex_to_hsl(c)) for c in candidates if hex_to_hsl(c)[1] >= min_sat]
    if not saturated:
        saturated = [(c, hex_to_hsl(c)) for c in candidates]

    def hue_dist(h):
        d = abs(h - target_hue)
        return min(d, 360 - d)

    return min(saturated, key=lambda x: hue_dist(x[1][0]))[0]

def find_lightest_desaturated(candidates, max_sat=0.35):
    soft = [(c, hex_to_hsl(c)) for c in candidates if hex_to_hsl(c)[1] <= max_sat]
    if not soft:
        soft = [(c, hex_to_hsl(c)) for c in candidates]
    return max(soft, key=lambda x: x[1][2])[0]

palette = dict(fallback)

if colors_path.exists():
    colors = parse_colors(colors_path)
    accents = [colors.get(f"COLOR{i}") for i in list(range(1, 7)) + list(range(8, 15))]
    accents = [c for c in accents if c]
    if accents:
        palette["love"] = find_closest(accents, 350, min_sat=0.25)
        palette["gold"] = find_closest(accents, 40,  min_sat=0.25)
        palette["pine"] = find_closest(accents, 200, min_sat=0.20)
        palette["foam"] = find_closest(accents, 175, min_sat=0.20)
        palette["iris"] = find_closest(accents, 280, min_sat=0.20)
        palette["rose"] = find_lightest_desaturated(accents)

        bg = colors.get("BACKGROUND", fallback["overlay"])
        r, g, b = int(bg[1:3],16)/255, int(bg[3:5],16)/255, int(bg[5:7],16)/255
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        l = min(1.0, l + 0.06)
        s = s * 0.8
        r2, g2, b2 = colorsys.hls_to_rgb(h, l, s)
        palette["overlay"] = f"#{int(r2*255):02x}{int(g2*255):02x}{int(b2*255):02x}"

if not starship_path.exists():
    sys.exit(0)

content = starship_path.read_text()
new_block = "\n".join([
    "[palettes.rose-pine]",
    *(f"{k} = '{palette[k]}'" for k in ("overlay", "love", "gold", "rose", "pine", "foam", "iris")),
])

pattern = re.compile(r"(?ms)^\[palettes\.rose-pine\]\n.*?(?=^\[)")
if pattern.search(content):
    content = pattern.sub(new_block + "\n\n", content, count=1)
else:
    content += "\n\n" + new_block + "\n"

output_path.write_text(content)
PY
}

write_kitty_from_setup() {
  python3 - "$OUTPUT_FILE" "$KITTY_PYWAL_FILE" <<'PY'
import colorsys
import sys
from pathlib import Path

def parse_colors(path):
    colors = {}
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        colors[key.strip()] = value.strip().strip("'")
    return colors

def hex_to_rgb(h):
    return tuple(int(h[i:i+2], 16) / 255 for i in (1, 3, 5))

def rgb_to_hex(rgb):
    return f"#{int(rgb[0]*255):02x}{int(rgb[1]*255):02x}{int(rgb[2]*255):02x}"

def rel_luminance(h):
    def channel(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = hex_to_rgb(h)
    r, g, b = channel(r), channel(g), channel(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast_ratio(a, b):
    l1, l2 = rel_luminance(a), rel_luminance(b)
    lighter, darker = max(l1, l2), min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)

def adjust_for_contrast(color, bg, ratio=4.5):
    if contrast_ratio(color, bg) >= ratio:
        return color

    h, l, s = colorsys.rgb_to_hls(*hex_to_rgb(color))
    bg_lum = rel_luminance(bg)
    direction = 1 if bg_lum < 0.5 else -1
    step = 0.04
    last = color

    for _ in range(30):
        l = min(1.0, l + step) if direction > 0 else max(0.0, l - step)
        last = rgb_to_hex(colorsys.hls_to_rgb(h, l, s))
        if contrast_ratio(last, bg) >= ratio:
            return last

    return "#ffffff" if bg_lum < 0.5 else "#000000"

colors = parse_colors(Path(sys.argv[1]))

bg = colors.get("BACKGROUND", "#1e1e2e")
fg = adjust_for_contrast(colors.get("FOREGROUND", "#cdd6f4"), bg, ratio=4.5)
cursor = adjust_for_contrast(colors.get("CURSOR", "#f5e0dc"), bg, ratio=4.5)

lines = [
    "# pywal-generated (enhanced)",
    f"foreground              {fg}",
    f"background              {bg}",
    f"selection_foreground    {bg}",
    f"selection_background    {cursor}",
    f"cursor                  {cursor}",
    f"cursor_text_color       {bg}",
    f"url_color               {colors.get('COLOR4', '#89b4fa')}",
]

target_hues = [0, 120, 60, 240, 300, 180]

def hex_hue(h):
    r, g, b = int(h[1:3],16)/255, int(h[3:5],16)/255, int(h[5:7],16)/255
    return colorsys.rgb_to_hls(r, g, b)[0] * 360

def lighten(hex_color, amount=0.15):
    r, g, b = int(hex_color[1:3],16)/255, int(hex_color[3:5],16)/255, int(hex_color[5:7],16)/255
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l = min(1.0, l + amount)
    r2, g2, b2 = colorsys.hls_to_rgb(h, l, s)
    return f"#{int(r2*255):02x}{int(g2*255):02x}{int(b2*255):02x}"

raw_accents = [
    adjust_for_contrast(colors.get(f"COLOR{i}", "#888888"), bg, ratio=4.5)
    for i in range(1, 7)
]
assigned = [None] * 6
used = set()

for slot_idx, target in enumerate(target_hues):
    def hue_dist(h):
        d = abs(hex_hue(h) - target)
        return min(d, 360 - d)
    candidates = [(i, hue_dist(c)) for i, c in enumerate(raw_accents) if i not in used]
    if candidates:
        best_i = min(candidates, key=lambda x: x[1])[0]
        assigned[slot_idx] = raw_accents[best_i]
        used.add(best_i)

remaining = [i for i in range(6) if i not in used]
for slot_idx in range(6):
    if assigned[slot_idx] is None:
        if remaining:
            assigned[slot_idx] = raw_accents[remaining.pop(0)]
        else:
            assigned[slot_idx] = "#888888"

lines.append(f"color0  {colors.get('COLOR0', '#45475a')}")
lines.append(f"color8  {colors.get('COLOR8', '#585b70')}")

for i, c in enumerate(assigned):
    lines.append(f"color{i+1}  {c}")
    lines.append(f"color{i+9}  {lighten(c, 0.1)}")

lines.append(f"color7  {colors.get('COLOR7', '#bac2de')}")
lines.append(f"color15 {colors.get('COLOR15', colors.get('COLOR7', '#a6adc8'))}")

Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
PY
}

WALLPAPER=""
if [ $# -gt 0 ]; then
  WALLPAPER="$1"
elif [ -n "${WALLPAPER_OVERRIDE:-}" ]; then
  WALLPAPER="$WALLPAPER_OVERRIDE"
else
  WALLPAPER=$(osascript -e 'tell app "finder" to get posix path of (get desktop picture as alias)' 2>/dev/null || true)
fi

if [ -z "$WALLPAPER" ]; then
  echo "Could not find current wallpaper."
  ensure_output_dir
  write_colors_setup
  write_kitty_fallback
  update_starship_palette
  exit 1
fi

echo "Current wallpaper: $WALLPAPER"
echo "Regenerating colors with pywal..."

WAL_CMD="$HOME/.local/bin/wal"
if [ ! -x "$WAL_CMD" ]; then
  WAL_CMD="wal"
fi

rm -rf "$WAL_CACHE_DIR"

if "$WAL_CMD" -i "$WALLPAPER" -n -q; then
  ensure_output_dir
  write_colors_setup
  write_kitty_from_setup
else
  echo "pywal failed. Applying fallbacks."
  ensure_output_dir
  write_colors_setup
  write_kitty_fallback
fi

update_starship_palette

echo "Reloading SketchyBar..."
sketchybar --reload

echo "Reloading JankyBorders..."
if pgrep -x "borders" >/dev/null; then
  killall borders
fi

echo "Colors synced."
