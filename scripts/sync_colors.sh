#!/usr/bin/env bash

set -uo pipefail

# GUI apps (Raycast, launchd agents) inherit a bare PATH of
# /usr/bin:/bin:/usr/sbin:/sbin. Two things break silently without Homebrew on
# it: pywal shells out to imagemagick and, when it is missing, writes no
# colors.json at all while still exiting 0 -- so the palette falls back to
# Catppuccin instead of the wallpaper's colors -- and `sketchybar --reload` at
# the end is not found. Fixing PATH here covers every caller.
PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$PATH"
export PATH

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOTFILES_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

WAL_CACHE_DIR="$HOME/.cache/wal"
OUTPUT_DIR="$HOME/.config/colors"
OUTPUT_FILE="$OUTPUT_DIR/setup.sh"
OUTPUT_FISH_FILE="$OUTPUT_DIR/setup.fish"
STARSHIP_OUTPUT_FILE="$OUTPUT_DIR/starship.toml"

KITTY_PYWAL_FILE="$DOTFILES_DIR/kitty/pywal-colors.conf"
STARSHIP_FILE="$DOTFILES_DIR/starship.toml"

STARSHIP_FALLBACK_OVERLAY="#26233a"
STARSHIP_FALLBACK_LOVE="#eb6f92"
STARSHIP_FALLBACK_GOLD="#f6c177"
STARSHIP_FALLBACK_ROSE="#ebbcba"
STARSHIP_FALLBACK_PINE="#31748f"
STARSHIP_FALLBACK_FOAM="#9ccfd8"
STARSHIP_FALLBACK_IRIS="#c4a7e7"

